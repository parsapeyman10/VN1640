ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / "dist" / "NBCM_CAN_Simulation_Package"
MAP = ROOT / "can_tester" / "assets" / "signal_map.json"

HS_BASE = 0x100      # first CAN id for high-speed frames
LS_BASE = 0x500      # first CAN id for low-speed frames
EXT = False          # standard 11-bit ids

HEADER = """/*@!Encoding:65001*/
/*============================================================================
  GENERATED by tools/build_package.py -- do not edit; change the workbook and
  regenerate.
============================================================================*/
"""


