DBC_README = """# Database files in this package

`NBCM_HS.dbc` and `NBCM_LS.dbc` are generated by `tools/build_package.py` from
`NBCM_Dena_CAN_Network_Map.xlsx`, which was itself exported from the official
databases (HS V23.0, LS V3.0).  This file records exactly how much of that is
authoritative.

## What is the real thing

Everything that decides whether a frame decodes:

* CAN identifiers (`{hs_n} HS` frames, `{ls_n} LS` frames, no duplicates)
* message names, senders, DLCs and cycle times
* per signal: start bit, length, byte order (Intel / Motorola), signedness,
  factor, offset, physical range and unit

So a value decoded from this database is the value the OEM database would give.

## Always true in a real vehicle

**One sender per frame.**  In the real networks each frame belongs to one ECU.
The restbus in `Nodes/` simulates 13 ECUs at once, so on a real bus you would
see a frame only while its sender is alive; here every frame is always present.

## How it was generated

The network map workbook stores its text as inline strings rather than in
`sharedStrings.xml`, so `load_netmap()` reads the sheets directly.  Rows are
taken verbatim: a message becomes one `BO_` line, a signal becomes one `SG_`
line with its own bit position, and the original comment is carried over as a
`CM_ SG_` line.

## Do not edit the generated files

Change the workbook (or the signal model) and run the tool again:

```bash
python tools/build_package.py
```

The package's own test rebuilds everything in a temporary directory and checks
all {hs_n} + {ls_n} frames and every signal against the workbook.
"""


