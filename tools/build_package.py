VECTOR_NO_NODE = "Vector__XXX"


def dbc_ident(name: str, fallback: str = "") -> str:
    """DBC identifiers: letters, digits, underscore; must not start with a digit.

    An empty name used to come out as a bare "_", which is not a node at all:
    the network map has exactly one message with no sender (LS_ID_TARA_PEPS_1,
    0x138), and its BO_ line therefore named a phantom node.  Callers pass
    fallback=Vector__XXX for a sender nobody knows.
    """
    name = (name or "").strip()
    if not name:
        return fallback or "_"
    out = "".join(c if (c.isalnum() or c == "_") else "_" for c in name)
    if out[0].isdigit():
        out = "_" + out
    return out


def _own_signal_count(data: dict) -> int:
    """How many model signals belong to a frame NBCM sends itself.

    Those are not simulated: the restbus fakes every *other* node, and on a real
    bench the NBCM being tested is the one on the bus.  The number is reported so
    "complete" can be checked instead of assumed.
    """
    try:
        nm = load_netmap(ROOT / "NBCM_CAN_Simulation_Package" / "1_Final"
                         / "NBCM_Dena_CAN_Network_Map.xlsx")
    except Exception:                                             # noqa: BLE001
        return 0
    senders = {m["MessageName"]: (m["Sender"] or "").strip().upper()
               for m in nm["messages"]}
    # the model only holds restbus-scope signals, so NBCM's own output is
    # everything the map defines minus what the model actually carries
    scope = [x for x in nm["signals"] if senders.get(x["MessageName"], "") != "NBCM"]
    return max(0, len(nm["signals"]) - len(scope))


def load_netmap(path: Path) -> dict:
    """Read the network map workbook: real ids, DLC and bit layout.

    ``NBCM_CAN_Simulation_Package/1_Final/NBCM_Dena_CAN_Network_Map.xlsx`` was
    exported from the official DBC files (HS V23.0, LS V3.0) and carries what the
    panel-binding workbook lacks: CAN ids, DLCs, start bits, lengths, byte order,
    scale and range.  Sheets are read directly because the file uses inline
    strings, not sharedStrings.xml.
    """
    import zipfile
    import xml.etree.ElementTree as ET

    ns = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
    z = zipfile.ZipFile(path)
    sheets = {n: f"xl/worksheets/sheet{i}.xml"
              for i, n in enumerate(
                  ["Overview", "Node_Tx_Matrix", "NBCM_Signals_Rx",
                   "HS_Messages", "HS_Signals", "LS_Messages", "LS_Signals"], 1)}

    def rows(name: str) -> list[list[str]]:
        root = ET.fromstring(z.read(sheets[name]))
        out = []
        for row in root.iter(f"{ns}row"):
            cells = []
            for c in row.iter(f"{ns}c"):
                txt = "".join(t.text or "" for t in c.iter(f"{ns}t"))
                if not txt:
                    txt = "".join(v.text or "" for v in c.iter(f"{ns}v"))
                cells.append(txt.strip())
            out.append(cells)
        return out

    def as_dicts(name: str) -> list[dict]:
        r = rows(name)
        head = r[0]
        return [dict(zip(head, x)) for x in r[1:] if x and x[0]]

    return {"messages": as_dicts("HS_Messages") + as_dicts("LS_Messages"),
            "signals": as_dicts("HS_Signals") + as_dicts("LS_Signals")}


def build_dbc(data: dict, net: str, frame_split: dict, netmap: dict) -> tuple[str, dict]:
    """Build one DBC for a network (HS or LS) from the real network map.

    Unlike the earlier synthesised version there is no frame splitting: the ids,
    DLCs and bit positions are the ones the OEM databases define, so a message is
    exactly one frame and ``frame_split`` only ever holds a single entry per
    message.  It is still filled in so adapt_restbus() stays a no-op pass-through
    and keeps working if a message ever needs splitting again.
    """
    nodes = sorted({m["Sender"].strip() for m in netmap["messages"]
                    if m["Network"] == net and m["Sender"].strip()})
    msgs = [m for m in netmap["messages"] if m["Network"] == net]
    sigs = [x for x in netmap["signals"] if x["Network"] == net]

    by_msg: dict[str, list[dict]] = {}
    for x in sigs:
        by_msg.setdefault(x["MessageName"], []).append(x)

    out = ['VERSION ""', "",
           "NS_ :", "\tNS_DESC_", "\tCM_", "\tBA_DEF_", "\tBA_", "\tVAL_",
           "\tCAT_DEF_", "\tCAT_", "\tFILTER", "\tBA_DEF_DEF_", "\tEV_DATA_",
           "\tENVVAR_DATA_", "\tSGTYPE_", "\tSGTYPE_VAL_", "\tBA_DEF_SGTYPE_",
           "\tBA_SGTYPE_", "\tSIG_TYPE_REF_", "\tVAL_TABLE_", "\tSIG_GROUP_",
           "\tSIG_VALTYPE_", "\tSIGTYPE_VALTYPE_", "\tBO_TX_BU_", "\tBA_DEF_REL_",
           "\tBA_REL_", "\tBA_DEF_DEF_REL_", "\tBU_SG_REL_", "\tBU_EV_REL_",
           "\tBU_BO_REL_", "\tSG_MUL_VAL_", "",
           "BS_:", "",
           "BU_: " + " ".join(dbc_ident(n) for n in nodes), ""]

    idmap = {}
    comments = []
    for m in sorted(msgs, key=lambda x: x["MessageName"]):
        name = m["MessageName"]
        can_id = int(m["MessageID_Dec"])
        dlc = int(m["DLC"])
        sender = m["Sender"]
        sig_list = by_msg.get(name, [])
        idmap[name] = {"id": can_id, "dlc": dlc, "signals": {}}
        frame_split.setdefault(name, []).append((name, [x["SignalName"] for x in sig_list]))

        # An unknown sender is "Vector__XXX", the DBC convention for "nobody
        # specific" -- not an invented node name.
        out.append(f"BO_ {can_id} {dbc_ident(name)}: {dlc} "
                   f"{dbc_ident(sender, fallback=VECTOR_NO_NODE)}")
        for x in sig_list:
            start = int(x["StartBit"])
            length = int(x["Length_bit"])
            # DBC: @1 is little-endian (Intel), @0 is big-endian (Motorola)
            order = 1 if x["ByteOrder"].lower().startswith("intel") else 0
            sign = "-" if x["Signed"].strip() in ("1", "true", "True") else "+"
            factor = float(x["Factor"] or 1)
            offset = float(x["Offset"] or 0)
            lo = float(x["Min"]) if x["Min"] else None
            hi = float(x["Max"]) if x["Max"] else None
            if lo is None or hi is None:
                raw = (0, 2 ** length - 1) if sign == "+" else (-(2 ** (length - 1)), 2 ** (length - 1) - 1)
                lo = raw[0] * factor + offset if lo is None else lo
                hi = raw[1] * factor + offset if hi is None else hi
            unit = (x["Unit"] or "").replace('"', "'")
            receivers = " ".join(dbc_ident(r) for r in (x["Receivers"] or "").split()
                                 if r) or "Vector__XXX"
            out.append(f" SG_ {dbc_ident(x['SignalName'])} : {start}|{length}@{order}"
                       f"{sign} ({factor:.9g},{offset:.9g}) [{lo:.9g}|{hi:.9g}] "
                       f"\"{unit}\" {receivers}")
            idmap[name]["signals"][x["SignalName"]] = {
                "start": start, "bits": length, "factor": factor, "offset": offset}
            if x["Comment"]:
                comments.append(f'CM_ SG_ {can_id} {dbc_ident(x["SignalName"])} '
                                f'"{x["Comment"].replace(chr(34), chr(39))}";')
        out.append("")
        comments.append(f'CM_ BO_ {can_id} "{sender} / {net}-CAN / '
                        f'cycle {m["CycleTime_ms"] or 0} ms";')

    out.append(f'CM_ "NBCM {net}-CAN database generated by tools/build_package.py '
               f'from the official network map";')
    out.extend(comments)
    out.append("")
    return "\n".join(out), idmap


def adapt_restbus(can: str, frame_split: dict) -> tuple[str, list[str]]:
    """Rewrite the restbus so its message objects match the frames in the DBC.

    A "message" in the workbook can hold up to 29 signals, which does not fit in
    one 8-byte CAN frame; build_dbc() therefore emits ``<name>``, ``<name>_2``,
    ...  The restbus still declares ``message <name> msg_<name>;``, writes every
    signal through ``msg_<name>`` and sends that single object.  Against the split
    DBC that both fails to compile (a signal is no longer in that frame) and
    never transmits the tail of the message.  Three shapes are rewritten:

        message <name> msg_<name>;   -> one declaration per emitted frame
        msg_<name>.<Sig> = ...;      -> the frame that owns <Sig>
        output(msg_<name>);          -> one output() per emitted frame

    ``frame_split`` maps ``original name -> [(frame_name, [signal, ...]), ...]``.
    """
    sig_owner: dict[str, dict[str, str]] = {}
    for base_name, frames in frame_split.items():
        for frame_name, sigs in frames:
            for sig in sigs:
                sig_owner.setdefault(base_name, {})[sig] = frame_name

    # A frame with a DLC but no signals is legal DBC and CANoe compiles it, so a
    # message that has no signals is kept as-is rather than dropped.  (The real
    # database has one: LS_ID_SUP_MMS, id 0x622, DLC 7, zero signals.)
    declared = set(re.findall(r"^\s*message\s+(\w+)\s+msg_\w+\s*;$", can, re.M))
    frameless = sorted(declared - set(frame_split))

    decl_re = re.compile(r"^(\s*)message\s+(\w+)\s+msg_(\w+)\s*;$")
    send_re = re.compile(r"^(\s*)output\(msg_(\w+)\);$")
    write_re = re.compile(r"\bmsg_(\w+)\.(\w+)(\s*=\s*[^;]+;)")

    moved = 0
    out: list[str] = []
    for line in can.splitlines():
        m = decl_re.match(line)
        if m and m.group(3) in frame_split:
            for frame_name, _ in frame_split[m.group(3)]:
                out.append(f"{m.group(1)}message {frame_name} msg_{frame_name};")
            continue

        m = send_re.match(line)
        if m and m.group(2) in frame_split:
            for frame_name, _ in frame_split[m.group(2)]:
                out.append(f"{m.group(1)}output(msg_{frame_name});")
            continue

        m = write_re.search(line)
        if m and m.group(1) in frame_split:
            base_name, sig = m.group(1), m.group(2)
            tgt = sig_owner.get(base_name, {}).get(sig)
            if tgt and tgt != base_name:
                out.append(line.replace(f"msg_{base_name}.{sig}",
                                        f"msg_{tgt}.{sig}", 1))
                moved += 1
                continue
        out.append(line)

    split = sorted(k for k, v in frame_split.items() if len(v) > 1)
    notes = [f"{len(split)} messages held more than 8 signals and were emitted as "
             f"several frames: {', '.join(split)}",
             f"{moved} signal writes were redirected to the frame that owns them"]
    if frameless:
        notes.append(f"{len(frameless)} message(s) are declared in the CAPL but have no "
                     f"frame in the network map: {', '.join(frameless)}")
    return "\n".join(out) + "\n", notes


