def adapt_restbus(can: str, frame_split: dict) -> tuple[str, list[str]]:
    """Rewrite the restbus so its message objects match the frames in the DBC.

    A "message" in the workbook can hold up to 29 signals, which does not fit in
    one 8-byte CAN frame; build_dbc() therefore emits ``<name>``, ``<name>_2``,
    ...  The restbus still declares ``message <name> msg_<name>;``, writes every
    signal through ``msg_<name>`` and sends that single object.  Against the split
    DBC that both fails to compile (a signal is no longer in that frame) and
    never transmits the tail of the message.  Three shapes are rewritten:

        message <name> msg_<name>;   -> one declaration per emitted frame
        msg_<name>.<Sig> = ...;      -> the frame that owns <Sig>
        output(msg_<name>);          -> one output() per emitted frame

    ``frame_split`` maps ``original name -> [(frame_name, [signal, ...]), ...]``.
    """
    sig_owner: dict[str, dict[str, str]] = {}
    for base_name, frames in frame_split.items():
        for frame_name, sigs in frames:
            for sig in sigs:
                sig_owner.setdefault(base_name, {})[sig] = frame_name

    # A message the workbook lists with zero signals cannot become a DBC frame (a
    # frame with no signals is rejected by CANoe), so it has no id either.  Its
    # declaration and its output() are commented out with an explanation rather
    # than left to fail compilation, and the fact is reported, never hidden.
    declared = set(re.findall(r"^\s*message\s+(\w+)\s+msg_\w+\s*;$", can, re.M))
    frameless = sorted(declared - set(frame_split))

    decl_re = re.compile(r"^(\s*)message\s+(\w+)\s+msg_(\w+)\s*;$")
    send_re = re.compile(r"^(\s*)output\(msg_(\w+)\);$")
    write_re = re.compile(r"\bmsg_(\w+)\.(\w+)(\s*=\s*[^;]+;)")

    moved = 0
    out: list[str] = []
    for line in can.splitlines():
        m = decl_re.match(line)
        if m and m.group(3) in frameless:
            out.append(f"  // no frame: the workbook declares {m.group(3)} with zero "
                       f"signals, so it has no CAN id")
            continue
        if m and m.group(3) in frame_split:
            for frame_name, _ in frame_split[m.group(3)]:
                out.append(f"{m.group(1)}message {frame_name} msg_{frame_name};")
            continue

        m = send_re.match(line)
        if m and m.group(2) in frameless:
            out.append(f"{m.group(1)}// nothing to send: {m.group(2)} has zero signals")
            continue
        if m and m.group(2) in frame_split:
            for frame_name, _ in frame_split[m.group(2)]:
                out.append(f"{m.group(1)}output(msg_{frame_name});")
            continue

        m = write_re.search(line)
        if m and m.group(1) in frame_split:
            base_name, sig = m.group(1), m.group(2)
            tgt = sig_owner.get(base_name, {}).get(sig)
            if tgt and tgt != base_name:
                out.append(line.replace(f"msg_{base_name}.{sig}",
                                        f"msg_{tgt}.{sig}", 1))
                moved += 1
                continue
        out.append(line)

    split = sorted(k for k, v in frame_split.items() if len(v) > 1)
    notes = [f"{len(split)} messages held more than 8 signals and were emitted as "
             f"several frames: {', '.join(split)}",
             f"{moved} signal writes were redirected to the frame that owns them"]
    if frameless:
        notes.append(f"{len(frameless)} message(s) have zero signals in the workbook, "
                     f"so they were commented out instead of given a frame: "
                     f"{', '.join(frameless)}")
    return "\n".join(out) + "\n", notes


