def write(path: Path, text: str, crlf: bool = True):
    path.parent.mkdir(parents=True, exist_ok=True)
    if crlf:
        text = text.replace("\r\n", "\n").replace("\n", "\r\n")
    path.write_bytes(text.encode("utf-8")) if crlf else path.write_text(text, encoding="utf-8")


def build(out: Path, with_tester: bool = False) -> dict:
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    data = json.loads(MAP.read_text(encoding="utf-8"))
    manifest = {"name": "NBCM_CAN_Simulation_Package",
                "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                "tool": "tools/build_package.py",
                "source": {"model": str(MAP.relative_to(ROOT)),
                           "restbus": "NBCM_Full_Restbus_Simulation.can"},
                "files": []}

    def add(rel: str, note: str):
        manifest["files"].append({"path": rel, "note": note})

    # --- databases ---------------------------------------------------------
    frame_split: dict[str, list[str]] = {}
    netmap_path = ROOT / "NBCM_CAN_Simulation_Package" / "1_Final" / "NBCM_Dena_CAN_Network_Map.xlsx"
    if not netmap_path.exists():
        raise SystemExit(f"missing network map, cannot build a real database: {netmap_path}"
                         "\n it carries the CAN ids and bit layouts; without it the"
                         " package would have to invent them again.")
    netmap = load_netmap(netmap_path)
    hs_xml, hs_ids = build_dbc(data, "HS", frame_split, netmap)
    ls_xml, ls_ids = build_dbc(data, "LS", frame_split, netmap)
    write(out / "Database" / "NBCM_HS.dbc", hs_xml)
    write(out / "Database" / "NBCM_LS.dbc", ls_xml)
    add("Database/NBCM_HS.dbc", f"{len(hs_ids)} messages (high-speed)")
    add("Database/NBCM_LS.dbc", f"{len(ls_ids)} messages (low-speed)")

    write(out / "Database" / "README.md",
          DBC_README.format(hs_n=len(hs_ids), ls_n=len(ls_ids)), crlf=False)
    add("Database/README.md", "where the ids and bit layouts come from")

    # --- nodes -------------------------------------------------------------
    restbus = (ROOT / "NBCM_Full_Restbus_Simulation.can").read_text(encoding="utf-8")
    restbus, restbus_notes = adapt_restbus(restbus, frame_split)
    write(out / "Nodes" / "Restbus.can", HEADER + restbus)
    for note in restbus_notes:
        print(f"  restbus: {note}")
    add("Nodes/Restbus.can", "the 13-node restbus simulation")

    shutil.copy2(ROOT / "canoe" / "NBCM_TesterBridge.can", out / "Nodes" / "TesterBridge.can")
    add("Nodes/TesterBridge.can", "system variable <-> restbus bridge")

    # The restbus #includes this file, so the package is broken without it.
    if (ROOT / "canoe" / "NBCM_Behaviour.can").exists():
        shutil.copy2(ROOT / "canoe" / "NBCM_Behaviour.can",
                     out / "Nodes" / "NBCM_Behaviour.can")
        add("Nodes/NBCM_Behaviour.can",
            "reaction rules: absent nodes report, substitute, cascade")

    # --- panel -------------------------------------------------------------
    panels = out / "Panels"
    panels.mkdir()
    for src in sorted((ROOT / "canoe" / "panels").glob("*.xvp")):
        shutil.copy2(src, panels / src.name)
    add("Panels/NBCM_Main.xvp", "the all-in-one panel (17 tabs)")

    # --- system variables --------------------------------------------------
    shutil.copy2(ROOT / "canoe" / "NBCM_Test.vsysvar",
                 out / "SystemVariables" / "NBCM_Test.vsysvar"
                 if (out / "SystemVariables").mkdir() is None
                 else out / "SystemVariables" / "NBCM_Test.vsysvar")
    add("SystemVariables/NBCM_Test.vsysvar", "508 system variables")

    # --- configuration -----------------------------------------------------


    # --- tester (optional) -------------------------------------------------
    if with_tester:
        for part in ("can_tester", "bridge", "tests"):
            src = ROOT / part
            if src.exists():
                shutil.copytree(src, out / "Tester" / part,
                                ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        add("Tester/", "the HTML tester and the bridge (optional)")

    # --- documentation -----------------------------------------------------
    pdfs = sorted((ROOT / "docs" / "pdf").glob("*.pdf"))
    for pdf in pdfs:
        d = out / "Documentation"
        d.mkdir(exist_ok=True)
        shutil.copy2(pdf, d / pdf.name)
    if pdfs:
        add("Documentation/", f"{len(pdfs)} Persian PDF guides")

    # --- entry points ------------------------------------------------------
    write(out / "START-HERE.txt", START_HERE, crlf=True)
    add("START-HERE.txt", "the 6 steps, in order")
    # counts come from the model and the map, never from a constant in the prose
    write(out / "README.md", PACKAGE_README.format(
        messages=len(hs_ids) + len(ls_ids),
        signals=len(data["signals"]),
        own=_own_signal_count(data),
        rest=len(data["signals"])), crlf=False)
    add("README.md", "what the package contains and what it cannot do")

    # the manifest lists every file that actually landed, not just the ones with
    # a handwritten note, so it can be used to verify a copied package
    present = sorted(p.relative_to(out).as_posix() for p in out.rglob("*") if p.is_file())
    present = [x for x in present if x != "manifest.json"]   # written by this block
    manifest["entry_points"] = manifest.pop("files")
    present = sorted(present + ["manifest.json"])       # this file, written below
    manifest["files"] = [{"path": rel,
                          "note": next((e["note"] for e in manifest["entry_points"]
                                        if e["path"] == rel), "")}
                         for rel in present]
    for entry in manifest["files"]:
        if entry["note"]:
            continue
        if entry["path"].startswith("Panels/"):
            entry["note"] = "CANoe panel (.xvp) -- add it with Home > Panel > Add"
        elif entry["path"].startswith("Documentation/"):
            entry["note"] = "Persian guide, PDF"
        elif entry["path"] == "manifest.json":
            entry["note"] = "this file"
    manifest["counts"] = {"files": len(present),
                          "messages": len(hs_ids) + len(ls_ids),
                          "signals": len(data["signals"])}
    write(out / "manifest.json", json.dumps(manifest, indent=2, ensure_ascii=False), crlf=False)
    return manifest


