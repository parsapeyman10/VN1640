PACKAGE_README = """# NBCM CAN Simulation Package

A ready-to-open CANoe 12 bench for the NBCM (Dena) network: 13 simulated ECUs,
97 messages, 481 signals, one panel that drives all of it, and a test suite.

See `START-HERE.txt` for the steps in order.  This file is the map.

## Layout

| Folder | What is in it |
|---|---|
| (no .cfg) | the configuration is built inside CANoe, see START-HERE.txt |
| `Database/` | generated `.dbc` for HS and LS (read the README there) |
| `Nodes/` | `Restbus.can` (all 13 ECUs) and `TesterBridge.can` (the bridge) |
| `Panels/` | `NBCM_Main.xvp` (17 tabs) plus one panel per node |
| `SystemVariables/` | `NBCM_Test.vsysvar` -- 508 variables |
| `Tester/` | the HTML tester and its bridge, if included |
| `Documentation/` | the Persian guides as PDF |

## Why there is no .cfg

A CANoe 12 configuration is a flat object stream that also carries the desktop
layout (GUID-tagged boxes per panel) and, for every CAPL node, the path of a
compiled `.cbf`.  Neither can be produced without CANoe.  A hand-written `.cfg`
compiles the files in the wrong order or points at a `.cbf` that does not exist,
and CANoe answers with exactly the error dialog this package is meant to avoid,
so the package ships the parts and `START-HERE.txt` builds the configuration in
about five minutes.  Once you have done that once, save it as `.cfg` (Ctrl+S)
and the copy next to it is a normal, fully working CANoe configuration.

## What works out of the box

* the restbus transmits on both networks, so CANoe's Trace shows traffic
* every signal is writable from the panel (set `DRIVE_MODE = 1` first)
* killing a node really stops its frames; the Monitor tab shows the age climb
* `SCENARIO_RUNNING = 1` drives a 20 s urban/highway cycle
* a suite run writes its verdict back into `TC_RESULT_PASS/FAIL`

## What is NOT real

**The CAN ids and bit layouts are synthesised.** The binding workbook has no
id, no DLC and no bit positions, so this package assigns them itself. That is
fine for exercising a toolchain and for demos, and wrong for anything that
compares against a real vehicle trace. Drop the real OEM `.dbc` files into
`Database/` and the rest of the package keeps working unchanged.
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="build the CANoe simulation package")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--with-tester", action="store_true",
                    help="also copy the HTML tester and bridge")
    args = ap.parse_args(argv)

    if not MAP.exists():
        print(f"error: {MAP} not found; run tools/build_data.py first")
        return 2

    m = build(args.out, args.with_tester)
    total = sum(f.stat().st_size for f in args.out.rglob("*") if f.is_file())
    print(f"package : {args.out}")
    print(f"files   : {len(m['files'])} entry points, "
          f"{len(list(args.out.rglob('*')))} paths, {total / 1024:.0f} KB")
    for f in m["files"]:
        print(f"  {f['path']:38} {f['note']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
