def dbc_ident(name: str) -> str:
    """DBC identifiers: letters, digits, underscore; must not start with a digit."""
    out = "".join(c if (c.isalnum() or c == "_") else "_" for c in name)
    if not out or out[0].isdigit():
        out = "_" + out
    return out


def signal_bits(kind: str, minimum: float, maximum: float) -> tuple[int, float, int]:
    """(bit length, factor, offset) for a signal, chosen so the range fits."""
    if kind in ("bool", "enum") and 0 <= minimum and maximum <= 255:
        return 8, 1.0, 0.0
    # physical range -> 16 bit unsigned with an offset
    if minimum < 0:
        span = max(maximum - minimum, 1.0)
        factor = span / 65535.0
        return 16, factor, minimum
    if maximum <= 255:
        return 8, 1.0, 0.0
    span = max(maximum, 1.0)
    factor = span / 65535.0
    return 16, factor, 0.0


def build_dbc(data: dict, net: str, frame_split: dict) -> tuple[str, dict]:
    """Build one DBC for a network (HS or LS) and the id/slot map it implies.

    ``frame_split`` is filled with ``original message name -> [frame names]`` so
    the restbus CAPL can be rewritten to match the frames that were emitted.
    """
    base = HS_BASE if net == "HS" else LS_BASE
    nodes = [n["node"] for n in data["nodes"] if n["net"] == net]
    # signal_map.json keeps messages and signals as separate lists: the message
    # records carry only counts, so group the signals by their message name.
    sigs_by_msg: dict[str, list[dict]] = {}
    for s in data["signals"]:
        if s["net"] == net:
            sigs_by_msg.setdefault(s["msg"], []).append(s)
    msgs = [{"msg": name, "cycle": sigs[0].get("cycle"), "net": net,
             "node": sigs[0]["node"]}
            for name, sigs in sigs_by_msg.items()]

    out = [f'VERSION ""', "",
           "NS_ :", "\tNS_DESC_", "\tCM_", "\tBA_DEF_", "\tBA_", "\tVAL_",
           "\tCAT_DEF_", "\tCAT_", "\tFILTER", "\tBA_DEF_DEF_", "\tEV_DATA_",
           "\tENVVAR_DATA_", "\tSGTYPE_", "\tSGTYPE_VAL_", "\tBA_DEF_SGTYPE_",
           "\tBA_SGTYPE_", "\tSIG_TYPE_REF_", "\tVAL_TABLE_", "\tSIG_GROUP_",
           "\tSIG_VALTYPE_", "\tSIGTYPE_VALTYPE_", "\tBO_TX_BU_", "\tBA_DEF_REL_",
           "\tBA_REL_", "\tBA_DEF_DEF_REL_", "\tBU_SG_REL_", "\tBU_EV_REL_",
           "\tBU_BO_REL_", "\tSG_MUL_VAL_", "",
           f"BS_:", "",
           "BU_: " + " ".join(dbc_ident(n) for n in nodes), ""]

    idmap = {}
    by_id = {s["id"]: s for s in data["signals"]}
    next_id = 0          # running CAN id: every emitted frame takes one
    for m in sorted(msgs, key=lambda x: x["msg"]):
        msg = m["msg"]
        sigs = sigs_by_msg.get(msg, [])
        if not sigs:
            continue

        # Lay the signals out in bit order.  A CAN frame is at most 8 bytes, and
        # a node here can carry 30+ signals in one "message", so a big message is
        # emitted as several frames: NBCM_<name>, NBCM_<name>_2, ...  Without
        # this, 103 of the 481 signals did not fit inside the frame they were
        # declared in.
        frames = []          # [(frame_name, [(signal, start, bits, factor, offset)])]
        cur_name, cur_slots, bit = msg, [], 0
        for s_ in sigs:
            bits, factor, offset = signal_bits(s_["kind"], s_["min"], s_["max"])
            if bits == 16 and bit % 16:
                bit += 16 - (bit % 16)          # keep 16-bit signals aligned
            if bit + bits > 64:                 # frame full: start the next one
                frames.append((cur_name, cur_slots))
                cur_name = f"{msg}_{len(frames) + 1}"
                cur_slots, bit = [], 0
            cur_slots.append((s_, bit, bits, factor, offset))
            bit += bits
        if cur_slots:
            frames.append((cur_name, cur_slots))

        for frame_name, slots in frames:
            can_id = base + next_id
            next_id += 1
            # the DLC must be computed from the slots *before* it is recorded,
            # otherwise it is written back as the previous frame's value
            dlc = max(1, (max(st + b for _, st, b, _, _ in slots) + 7) // 8)
            idmap[frame_name] = {"id": can_id, "dlc": dlc, "signals": {}}
            frame_split.setdefault(msg, []).append(
                (frame_name, [x[0]["sig"] for x in slots]))
            out.append(f"BO_ {can_id} {dbc_ident(frame_name)}: {dlc} "
                       f"{dbc_ident(slots[0][0]['node'])}")
            for s_, start, bits_, factor, offset in slots:
                unit = s_["unit"] or ""
                out.append(
                    f" SG_ {dbc_ident(s_['sig'])} : {start}|{bits_}@1+ "
                    f"({factor:.9g},{offset:.9g}) [{s_['min']:.9g}|{s_['max']:.9g}] "
                    f"\"{unit}\" {dbc_ident(s_['node'])}")
                idmap[frame_name]["signals"][s_["sig"]] = {
                    "start": start, "bits": bits_, "factor": factor, "offset": offset}
            out.append("")

    # comments carry the human meaning the workbook had
    out.append("CM_ \"Generated simulator database: CAN ids and bit layout are"
               " synthesised (see Database/README.md).\";")
    next_id = 0          # running CAN id: every emitted frame takes one
    for m in sorted(msgs, key=lambda x: x["msg"]):
        msg = m["msg"]
        if msg in idmap:
            sigs = sigs_by_msg.get(msg, [])
            node = sigs[0]["node"] if sigs else "?"
            out.append(f"CM_ BO_ {idmap[msg]['id']} \"{node} / {net}-CAN"
                       f" / cycle {m.get('cycle') or 0} ms\";")
    out.append("")
    return "\n".join(out), idmap


