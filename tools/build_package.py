DBC_README = """# Database files in this package

`NBCM_HS.dbc` and `NBCM_LS.dbc` are **generated**, and it is worth knowing
exactly what that means before you trust a decoded value.

## What is real

* node names, message names and signal names (from the binding workbook)
* each signal's physical range, unit and default value
* which node carries which message, and the cycle time

## What is synthesised

The workbook has **no CAN identifier, no DLC and no bit layout**, so this tool
invented them:

* message ids: `{hs_base:#x}` and up for HS, `{ls_base:#x}` and up for LS, one
  id per message in alphabetical order ({hs_n} HS, {ls_n} LS)
* bit layout: signals are packed in order, each in its own slot -- 8 bits for a
  boolean or small enum, 16 bits (offset encoded) for a wider physical range
* DLC: as small as the packed signals allow, capped at 8 bytes

## Consequence

The package is a **simulator**: the restbus transmits, the panel binds to real
symbols, timeouts are real (a killed node stops transmitting), and the CAPL
compiles against these databases.  But the addresses and bit positions are
**not** the OEM ones, so:

* do not compare this against a trace taken from the real vehicle
* do not use it to validate a real ECU's decoding

If you have `NBCM_ALL_CAN_HS_Database_V23_0_030920.dbc` and
`NBCM_ALL_CAN_LS_Database_V3_0_030920.dbc` (they are named in the header of the
restbus file), drop them into `Database/`, delete the two generated files, and
re-point the configuration at them.  Everything else in the package -- panels,
system variables, CAPL bridge, tester -- keeps working, and then the ids and
layouts **are** the real ones.
"""

