def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="build the CANoe simulation package")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--with-tester", action="store_true",
                    help="also copy the HTML tester and bridge")
    args = ap.parse_args(argv)

    if not MAP.exists():
        print(f"error: {MAP} not found; run tools/build_data.py first")
        return 2

    m = build(args.out, args.with_tester)
    total = sum(f.stat().st_size for f in args.out.rglob("*") if f.is_file())
    print(f"package : {args.out}")
    print(f"files   : {len(m['files'])} entry points, "
          f"{len(list(args.out.rglob('*')))} paths, {total / 1024:.0f} KB")
    for f in m["files"]:
        print(f"  {f['path']:38} {f['note']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
