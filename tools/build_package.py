"""
build_package.py -- assemble a self-contained CANoe simulation package
======================================================================
Produces dist/NBCM_CAN_Simulation_Package/ laid out the way a Vector sample
configuration is laid out, so it can be zipped, handed to a colleague and
opened in CANoe 12 on a fresh PC:

    NBCM_CAN_Simulation_Package/
      Setup/README-FIRST.txt       <- the 5-minute build inside CANoe (no .cfg)
      Database/NBCM_HS.dbc         <- generated from the signal model
      Database/NBCM_LS.dbc
      Nodes/Restbus.can            <- the restbus from NBCM_Full_Restbus_Simulation.can
      Nodes/TesterBridge.can       <- canoe/NBCM_TesterBridge.can
      Panels/NBCM_Main.xvp         <- the all-in-one panel
      Panels/*.xvp                 <- per-node panels + smoke
      SystemVariables/NBCM_Test.vsysvar
      Tester/                      <- the HTML tester + bridge (optional but handy)
      Documentation/               <- the Persian PDFs
      README.md, START-HERE.txt    <- what to do, in order
      manifest.json                <- what is in the package and where it came from

Honest limits, because they matter here:

* **The .dbc files are synthesised.** The workbook has node / message / signal
  / cycle time but no CAN id, no DLC and no bit layout, so ids are assigned in
  a documented, collision-free way and every signal gets its own 1-bit or
  8-bit slot.  That is enough for CANoe to compile the CAPL and show the
  symbols, but the package works as a **simulator**, not as a faithful decode
  of the real vehicle: addresses and layouts will differ from the OEM database.
  See Database/README.md in the package.
* **There is no pre-built .cfg, on purpose.** A CANoe 12 configuration is a flat
  object stream that also embeds the desktop layout (GUID-tagged boxes) and, per
  CAPL node, a compiled .cbf path.  Neither can be produced outside CANoe, and a
  half-right streamer file is exactly the "error dialog on open" this package is
  supposed to avoid.  So the package ships the parts plus a short, verified
  build-it-inside-CANoe path instead of a file that might refuse to open.

    python tools/build_package.py
    python tools/build_package.py --with-tester      # include the HTML app
    python tools/build_package.py --out /tmp/pkg
"""

