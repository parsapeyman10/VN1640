/* ==========================================================================
   info.js — the (i) buttons: what is this signal, what does it do
   --------------------------------------------------------------------------
   Every signal row, every node card and every message carries a small circled
   "!". Hovering it shows a short version; clicking it opens the full
   explanation. The text comes from assets/descriptions.js, which is generated by
   tools/signal_glossary.py — the same source the CANoe panel tooltips use.
   ========================================================================== */
(function (global) {
  'use strict';
  const C = global.Core;
  const D = global.NBCM_DESCRIPTIONS || { nodes: {}, signals: {} };

  const $ = (id) => document.getElementById(id);

  const el = (tag, attrs, kids) => {
    const n = document.createElement(tag);
    if (attrs) Object.keys(attrs).forEach((k) => {
      if (k === 'class') n.className = attrs[k];
      else if (k === 'text') n.textContent = attrs[k];
      else n.setAttribute(k, attrs[k]);
    });
    (kids || []).forEach((c) => { if (c) n.appendChild(typeof c === 'string' ? document.createTextNode(c) : c); });
    return n;
  };

  function record(id, sig, node) {
    if (id && D.signals[id]) return D.signals[id];
    // the same signal in a second frame, or a node-level request
    if (sig) {
      const k = Object.keys(D.signals).find((x) => D.signals[x].name === sig);
      if (k) return D.signals[k];
    }
    if (node && D.nodes[node]) {
      return { title: node, nodeTitle: D.nodes[node].title, about: D.nodes[node].about,
               facts: [], notes: [], message: '', cycle: 0, kind: '' };
    }
    return null;
  }

  /** Short text used for the native hover tooltip. */
  function hoverText(rec) {
    if (!rec) return '';
    const lines = [rec.title + (rec.node ? ' — ' + rec.node : '')];
    if (rec.about) lines.push(rec.about);
    if (rec.notes && rec.notes.length) lines.push(rec.notes.join(' · '));
    const f = (rec.facts || []).filter((x) => /پیام|چرخه|بازه|واحد/.test(x));
    if (f.length) lines.push(f.join('\n'));
    lines.push('برای توضیح کامل کلیک کنید');
    const t = lines.join('\n');
    return t.length > 900 ? t.slice(0, 899) + '…' : t;
  }

  /** The (i) control itself. */
  function button(rec, label) {
    const b = el('button', {
      class: 'infobtn',
      type: 'button',
      'aria-label': 'توضیح: ' + (rec ? rec.title : (label || '')),
      title: hoverText(rec),
    }, ['!']);
    b.addEventListener('click', (e) => { e.stopPropagation(); e.preventDefault(); open(rec, label); });
    return b;
  }

  /** The full explanation, as a modal. */
  function open(rec, label) {
    const box = $('infoBox');
    if (!box) return;
    const body = $('infoBody');
    body.innerHTML = '';
    if (!rec) {
      body.appendChild(el('h3', { text: label || '' }));
      body.appendChild(el('p', { class: 'muted', text: 'برای این مورد توضیحی ثبت نشده است.' }));
    } else {
      body.appendChild(el('h3', { text: rec.title }));
      const sub = el('div', { class: 'infosub' });
      if (rec.node) sub.appendChild(el('span', { class: 'chip', text: rec.node + (rec.nodeTitle ? ' — ' + rec.nodeTitle : '') }));
      if (rec.message) sub.appendChild(el('span', { class: 'chip mono', text: rec.message }));
      if (rec.net) sub.appendChild(el('span', { class: 'chip', text: rec.net + '-CAN' }));
      if (rec.cycle) sub.appendChild(el('span', { class: 'chip', text: 'هر ' + rec.cycle + ' ms' }));
      if (rec.name) sub.appendChild(el('span', { class: 'chip mono', text: rec.name }));
      body.appendChild(sub);

      body.appendChild(el('h4', { text: 'این چیست و چه کاری می‌کند' }));
      body.appendChild(el('p', { text: rec.about || '—' }));

      if (rec.notes && rec.notes.length) {
        body.appendChild(el('h4', { text: 'نکته‌های کاربردی' }));
        const ul = el('ul');
        rec.notes.forEach((n) => ul.appendChild(el('li', { text: n })));
        body.appendChild(ul);
      }

      if (rec.facts && rec.facts.length) {
        body.appendChild(el('h4', { text: 'مشخصات فنی' }));
        const tb = el('table', { class: 'infotbl' });
        rec.facts.forEach((f) => {
          const tr = el('tr');
          const [k, ...rest] = f.split(': ');
          if (rest.length) {
            tr.appendChild(el('td', { class: 'k', text: k }));
            tr.appendChild(el('td', { text: rest.join(': ') }));
          } else {
            tr.appendChild(el('td', { colspan: '2', text: f }));
          }
          tb.appendChild(tr);
        });
        body.appendChild(tb);
      }

      // live value, so the popup also answers "what is it doing right now"
      if (rec.name && C.values && C.values[rec.name] !== undefined) {
        const v = C.values[rec.name];
        body.appendChild(el('h4', { text: 'مقدار فعلی روی باس' }));
        body.appendChild(el('p', { class: 'liveval', text: String(v) + (rec.unit ? ' ' + rec.unit : '') }));
      }
      if (rec.kind === 'bool') {
        body.appendChild(el('p', { class: 'muted', text: 'دو حالته: ۱ یعنی روشن/فعال، ۰ یعنی خاموش/غیرفعال.' }));
      }
    }
    $('infoTitle').textContent = 'راهنمای سیگنال';
    box.classList.add('show');
    box.setAttribute('aria-hidden', 'false');
  }

  function close() {
    const box = $('infoBox');
    if (!box) return;
    box.classList.remove('show');
    box.setAttribute('aria-hidden', 'true');
  }

  function init() {
    const box = $('infoBox');
    if (!box) return;
    box.querySelector('.infoclose').addEventListener('click', close);
    box.addEventListener('click', (e) => { if (e.target === box) close(); });
    document.addEventListener('keydown', (e) => { if (e.key === 'Escape') close(); });
  }

  global.Info = { button, open, close, init, record, hoverText, data: D };
})(window);
